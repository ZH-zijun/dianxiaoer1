| **加单** | "3号桌再加5个蚕蛹" | 在 3 号桌已有订单中追加明细 |
| **结账** | "3号桌结账" | 汇总 3 号桌所有消费，标记已清台 |
| **改单** | "3号桌羊肉串改20个" | 修改已有订单明细的数量 |
| **退单** | "3号桌肉筋儿不要了" | 删除已有订单中的明细 |
| **询价** | "鸡翅多少钱" | 查询品类表中鸡翅的价格 |
| **新品定价** | "蚕蛹8块一份" | 将蚕蛹加入品类表，价格 8 元 |

## 输出格式

对于每条语音输入，必须返回严格的 JSON 格式：

{
  "action": "<动作类型>",
  "table_no": "<桌号>",
  "items": [
    {
      "name": "<品名>",
      "quantity": <数量>,
      "unit_price": <单价>,
      "is_new": <true|false>
    }
  ],
  "total": <合计金额>,
  "message": "<给用户看的反馈文字>"
}

action 枚举：new_order / add_items / close_order / update_item / remove_item / query_price / set_price

